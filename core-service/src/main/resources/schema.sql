-- =====================================================================
-- Esquema relacional del core-service. Replica el DER del alumno.
-- Única diferencia (decisión S1): en PACIENTE y PROFESIONAL la PK es
-- también la FK a USUARIO (herencia JOINED del UML).
-- Se ejecuta en cada arranque: por eso "IF NOT EXISTS".
-- =====================================================================

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(150) NOT NULL UNIQUE,
    password    VARCHAR(100) NOT NULL,          -- hash BCrypt (S11)
    apellido    VARCHAR(100) NOT NULL,
    nombre      VARCHAR(100) NOT NULL,
    rol         VARCHAR(20)  NOT NULL           -- ADMIN, PROFESIONAL, PACIENTE
);

-- S1: id_paciente es PK y FK a usuario
CREATE TABLE IF NOT EXISTS paciente (
    id_paciente       INTEGER PRIMARY KEY REFERENCES usuario (id_usuario),
    dni               VARCHAR(20) NOT NULL,
    fecha_nacimiento  DATE        NOT NULL
);

-- S1: id_profesional es PK y FK a usuario
CREATE TABLE IF NOT EXISTS profesional (
    id_profesional  INTEGER PRIMARY KEY REFERENCES usuario (id_usuario),
    matricula       VARCHAR(30)  NOT NULL,
    especialidad    VARCHAR(100) NOT NULL
);

-- 1 a 1 con paciente (FK UNIQUE)
CREATE TABLE IF NOT EXISTS expediente_clinico (
    id_expediente            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente              INTEGER NOT NULL UNIQUE REFERENCES paciente (id_paciente),
    antecedentes             VARCHAR(2000),
    fecha_creacion           DATE NOT NULL,
    observaciones_generales  VARCHAR(2000)
);

CREATE TABLE IF NOT EXISTS cita (
    id_cita         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profesional  INTEGER     NOT NULL REFERENCES profesional (id_profesional),
    id_paciente     INTEGER     NOT NULL REFERENCES paciente (id_paciente),
    estado          VARCHAR(20) NOT NULL,       -- RESERVADA, CANCELADA, ATENDIDA (S9)
    motivo          VARCHAR(255),
    fecha_hora      TIMESTAMP   NOT NULL
);

CREATE TABLE IF NOT EXISTS consulta (
    id_consulta     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita         INTEGER   NOT NULL REFERENCES cita (id_cita),
    id_profesional  INTEGER   NOT NULL REFERENCES profesional (id_profesional),
    id_expediente   INTEGER   NOT NULL REFERENCES expediente_clinico (id_expediente),
    observaciones   VARCHAR(2000),
    fecha_consulta  TIMESTAMP NOT NULL,
    indicaciones    VARCHAR(2000)
);

-- S2: 0..1 diagnóstico por consulta (id_consulta UNIQUE)
CREATE TABLE IF NOT EXISTS diagnostico (
    id_diagnostico  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta     INTEGER NOT NULL UNIQUE REFERENCES consulta (id_consulta),
    descripcion     VARCHAR(2000) NOT NULL,
    fecha           DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS dispositivo_iot (
    id_dispositivo    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente       INTEGER     NOT NULL REFERENCES paciente (id_paciente),
    tipo              VARCHAR(50) NOT NULL,     -- OXIMETRO, TENSIOMETRO, PULSERA, TERMOMETRO
    estado            VARCHAR(20) NOT NULL,     -- ACTIVO, INACTIVO (S9)
    ultima_actividad  TIMESTAMP
);

-- S3: la alerta vive en la base del core. id_profesional puede ser null (S12)
CREATE TABLE IF NOT EXISTS alerta_medica (
    id_alerta       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente     INTEGER      NOT NULL REFERENCES paciente (id_paciente),
    id_profesional  INTEGER      REFERENCES profesional (id_profesional),
    nivel           VARCHAR(20)  NOT NULL,      -- ALTA, CRITICA
    mensaje         VARCHAR(500) NOT NULL,
    estado          VARCHAR(20)  NOT NULL,      -- GENERADA, ATENDIDA
    fecha_hora      TIMESTAMP    NOT NULL
);
